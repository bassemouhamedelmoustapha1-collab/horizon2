// Élargit les types littéraux ("Se connecter") en `string` pour que
// les dictionnaires FR et EN partagent une même forme structurelle.
type Widen<T> = T extends string
  ? string
  : { [K in keyof T]: Widen<T[K]> };

export type Dictionary = Widen<(typeof dictionaries)["fr"]>;

export function getDictionary(lang: Lang): Dictionary {
  return dictionaries[lang];
}
